/*
 * QA-3: every third-party library is served from this origin, listed in
 * assets/vendor/VENDOR.json (generated by tools/vendor.mjs) together with its
 * version, sha256 and sha384. Nothing is fetched from a CDN, so the page
 * cannot be broken or hijacked by one, and each tag carries an integrity hash
 * so a tampered file fails closed instead of executing.
 */
$vendorManifest = null;
$vendorPath = __DIR__ . '/assets/vendor/VENDOR.json';
if (is_readable($vendorPath)) {
    $decoded = json_decode((string)file_get_contents($vendorPath), true);
    if (is_array($decoded)) {
        $vendorManifest = $decoded;
    }
}

/*
 * QA-4: in a deploy, the bundle and the stylesheet are content-hashed and
 * named by assets/build-manifest.json (tools/build.mjs --prod). The manifest
 * also carries their sha384, so our own two files are integrity-checked like
 * the vendored ones. Without a manifest (a dev checkout) the unversioned dev
 * build is used instead.
 */
$buildManifest = null;
$buildPath = __DIR__ . '/assets/build-manifest.json';
if (is_readable($buildPath)) {
    $decoded = json_decode((string)file_get_contents($buildPath), true);
    if (is_array($decoded) && isset($decoded['js']['file'], $decoded['css']['file'])
        && is_file(__DIR__ . '/' . $decoded['js']['file']) && is_file(__DIR__ . '/' . $decoded['css']['file'])) {
        $buildManifest = $decoded;
    }
}

/*
 * QA-3 deploy check: the integrity hashes only mean anything if the bytes that
 * arrive at the browser are the bytes in the manifest. A transfer that rewrites
 * line endings (FTP in ASCII mode, a Windows editor, a plain `cp` through a
 * text-mode tool) changes every size in assets/vendor/VENDOR.json and makes the
 * browser block the file — from the operator's side: a blank dashboard and a
 * console error. stat() is metadata, so compare every declared size on each
 * render and say so in the page instead of failing silently.
 */
$deployProblems = [];
$checkBytes = static function (string $relative, int $expected, string $label) use (&$deployProblems): void {
    $full = __DIR__ . '/' . $relative;
    if (!is_file($full)) {
        $deployProblems[] = $label . ' is missing (' . $relative . ')';
        return;
    }
    $actual = filesize($full);
    if ($actual !== $expected) {
        $deployProblems[] = sprintf(
            '%s is %s bytes on disk but %s in the manifest (%s)',
            $label,
            number_format($actual),
            number_format($expected),
            $relative
        );
    }
};
if ($vendorManifest !== null) {
    foreach (($vendorManifest['files'] ?? []) as $entry) {
        if (isset($entry['target'], $entry['bytes'])) {
            $checkBytes((string)$entry['target'], (int)$entry['bytes'], (string)($entry['id'] ?? 'vendor file'));
        }
    }
}
if ($buildManifest !== null) {
    $checkBytes((string)$buildManifest['js']['file'], (int)$buildManifest['js']['bytes'], 'the bundle');
    $checkBytes((string)$buildManifest['css']['file'], (int)$buildManifest['css']['bytes'], 'the stylesheet');
}

function assetTag(array $entry, string $kind): string
{
    $integrity = isset($entry['sha384'])
        ? ' integrity="sha384-' . htmlspecialchars((string)$entry['sha384'], ENT_QUOTES) . '"'
        : '';
    if ($kind === 'js') {
        return '  <script defer src="' . htmlspecialchars((string)$entry['file'], ENT_QUOTES) . '"' . $integrity . '></script>';
    }
    return '  <link rel="stylesheet" href="' . htmlspecialchars((string)$entry['file'], ENT_QUOTES) . '"' . $integrity . '>';
}

$asset = static function (string $relative): string {
    /* Cache-busting for our own files (QA-4): the build writes the hash into
     * the filename, so this is a straight path, but keep the helper in one
     * place for the dev build too. */
    return htmlspecialchars($relative, ENT_QUOTES);
};

function vendorTag(array $entry): string
{
    $integrity = isset($entry['integrity']) ? ' integrity="' . htmlspecialchars((string)$entry['integrity'], ENT_QUOTES) . '"' : '';
    if (($entry['tag'] ?? '') === 'script') {
        $defer = !empty($entry['defer']) ? ' defer' : '';
        return '  <script' . $defer . ' src="' . htmlspecialchars((string)$entry['src'], ENT_QUOTES) . '"' . $integrity . '></script>';
    }
    return '  <link rel="stylesheet" href="' . htmlspecialchars((string)$entry['href'], ENT_QUOTES) . '"' . $integrity . '>';
}
