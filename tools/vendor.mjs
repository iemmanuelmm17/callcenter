#!/usr/bin/env node
/**
 * Vendor the third-party front-end libraries into assets/vendor/ (QA-3).
 *
 * The page used to load React, ReactDOM and Chart.js from unpkg/jsdelivr at
 * parse time and Tabulator (JS + CSS) from unpkg the first time a drill-down
 * opened, with no integrity hashes. That is a supply-chain dependency on two
 * public CDNs and a hard failure on any network that blocks them — for an app
 * whose only other outbound call is to the customer's own PBX.
 *
 * After this tool runs, the application makes no third-party requests at all.
 *
 *   node tools/vendor.mjs            # copy the pinned files + write the manifest
 *   node tools/vendor.mjs --check    # verify the committed files match the manifest
 *
 * The files are copied out of the *pinned npm packages* (devDependencies), not
 * downloaded from a CDN, so `npm ci` + this tool is the whole provenance story,
 * and every file's hash is recorded in assets/vendor/VENDOR.json. The test
 * suite runs --check, so a hand-edited vendor file fails the build.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MODULES = path.join(ROOT, 'node_modules');
const OUT = path.join(ROOT, 'assets/vendor');
const MANIFEST = path.join(OUT, 'VENDOR.json');
const check = process.argv.includes('--check');

/* Package -> version is read from the manifest's own sources so a stale
 * package.json pin cannot silently vendor something else. */
const pkgVersion = name => JSON.parse(readFileSync(path.join(MODULES, name, 'package.json'), 'utf8')).version;

const FILES = [
  /* id, package, source inside the package, destination inside assets/vendor */
  ['react', 'react', 'umd/react.production.min.js', 'react/react.production.min.js'],
  ['react-dom', 'react-dom', 'umd/react-dom.production.min.js', 'react-dom/react-dom.production.min.js'],
  ['chartjs', 'chart.js', 'dist/chart.umd.js', 'chart.js/chart.umd.js'],
  ['tabulator-js', 'tabulator-tables', 'dist/js/tabulator.min.js', 'tabulator/tabulator.min.js'],
  ['tabulator-css', 'tabulator-tables', 'dist/css/tabulator_midnight.min.css', 'tabulator/tabulator_midnight.min.css'],
  ['fontawesome-css', '@fortawesome/fontawesome-free', 'css/all.min.css', 'fontawesome/css/all.min.css'],
  ['fontawesome-solid', '@fortawesome/fontawesome-free', 'webfonts/fa-solid-900.woff2', 'fontawesome/webfonts/fa-solid-900.woff2'],
  ['fontawesome-regular', '@fortawesome/fontawesome-free', 'webfonts/fa-regular-400.woff2', 'fontawesome/webfonts/fa-regular-400.woff2'],
  ['fontawesome-brands', '@fortawesome/fontawesome-free', 'webfonts/fa-brands-400.woff2', 'fontawesome/webfonts/fa-brands-400.woff2'],
  ['plex-500', '@fontsource/ibm-plex-mono', 'files/ibm-plex-mono-latin-500-normal.woff2', 'ibm-plex-mono/ibm-plex-mono-latin-500-normal.woff2'],
  ['plex-600', '@fontsource/ibm-plex-mono', 'files/ibm-plex-mono-latin-600-normal.woff2', 'ibm-plex-mono/ibm-plex-mono-latin-600-normal.woff2'],
  ['plex-700', '@fontsource/ibm-plex-mono', 'files/ibm-plex-mono-latin-700-normal.woff2', 'ibm-plex-mono/ibm-plex-mono-latin-700-normal.woff2']
];

const LICENSES = [
  ['react', 'LICENSE', 'licenses/react-LICENSE'],
  ['react-dom', 'LICENSE', 'licenses/react-dom-LICENSE'],
  ['chart.js', 'LICENSE.md', 'licenses/chart.js-LICENSE.md'],
  ['tabulator-tables', 'LICENSE', 'licenses/tabulator-tables-LICENSE'],
  ['@fortawesome/fontawesome-free', 'LICENSE.txt', 'licenses/fontawesome-free-LICENSE.txt'],
  ['@fontsource/ibm-plex-mono', 'LICENSE', 'licenses/ibm-plex-mono-LICENSE']
];

/* The mono face the app uses (weights 500/600/700), served from the vendored
 * woff2 files instead of fonts.googleapis.com. */
const PLEX_CSS = `/* IBM Plex Mono 500/600/700, self-hosted (QA-3).
 * Generated by tools/vendor.mjs from @fontsource/ibm-plex-mono — do not edit. */
${[500, 600, 700].map(weight => `@font-face {
  font-family: 'IBM Plex Mono';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('./ibm-plex-mono-latin-${weight}-normal.woff2') format('woff2');
}`).join('\n')}
`;

/* What portal.php loads, in order. Tabulator is deliberately absent: it is
 * injected on first use by ensureTabulator(), which reads the same manifest. */
const LOAD = [
  { tag: 'stylesheet', id: 'fontawesome-css', href: 'assets/vendor/fontawesome/css/all.min.css' },
  { tag: 'stylesheet', id: 'plex-mono-css', href: 'assets/vendor/ibm-plex-mono/plex-mono.css' },
  { tag: 'script', id: 'react', src: 'assets/vendor/react/react.production.min.js', defer: true },
  { tag: 'script', id: 'react-dom', src: 'assets/vendor/react-dom/react-dom.production.min.js', defer: true },
  { tag: 'script', id: 'chartjs', src: 'assets/vendor/chart.js/chart.umd.js', defer: true }
];

const sha = (buffer, algorithm, encoding) => createHash(algorithm).update(buffer).digest(encoding);

if (check) {
  if (!existsSync(MANIFEST)) {
    console.error('assets/vendor/VENDOR.json is missing — run `node tools/vendor.mjs`');
    process.exit(1);
  }
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const problems = [];
  for (const file of manifest.files) {
    const absolute = path.join(ROOT, file.target);
    if (!existsSync(absolute)) {
      problems.push(`missing: ${file.target}`);
      continue;
    }
    const buffer = readFileSync(absolute);
    if (sha(buffer, 'sha256', 'hex') !== file.sha256) problems.push(`changed: ${file.target}`);
  }
  for (const entry of manifest.load) {
    const file = manifest.files.find(f => f.id === entry.id);
    if (file && file.integrity && entry.integrity !== file.integrity) {
      problems.push(`integrity mismatch in the load list: ${entry.id}`);
    }
  }
  if (problems.length) {
    console.error('vendor check FAILED:\n  ' + problems.join('\n  '));
    console.error('run `node tools/vendor.mjs` to refresh the vendored files');
    process.exit(1);
  }
  console.log(`vendor check OK — ${manifest.files.length} files match VENDOR.json (${manifest.versions.join(', ')})`);
  process.exit(0);
}

if (!existsSync(MODULES)) {
  console.error('node_modules is missing — run `npm ci` first');
  process.exit(1);
}

const files = [];
const versions = new Set();

for (const [id, pkg, from, to] of FILES) {
  const source = path.join(MODULES, pkg, from);
  if (!existsSync(source)) {
    console.error(`missing ${pkg}/${from} — run \`npm ci\` (is ${pkg} in devDependencies?)`);
    process.exit(1);
  }
  const target = path.join(OUT, to);
  mkdirSync(path.dirname(target), { recursive: true });
  copyFileSync(source, target);
  const buffer = readFileSync(target);
  const version = pkgVersion(pkg);
  versions.add(`${pkg}@${version}`);
  files.push({ id, package: pkg, version, from: `${pkg}/${from}`, target: `assets/vendor/${to}`, bytes: buffer.length, sha256: sha(buffer, 'sha256', 'hex'), sha384: sha(buffer, 'sha384', 'base64') });
  console.log(`  ${to.padEnd(52)} ${String((buffer.length / 1024).toFixed(1)).padStart(8)} kB  ${pkg}@${version}`);
}

/* The generated stylesheet for the mono face. */
const plexTarget = path.join(OUT, 'ibm-plex-mono/plex-mono.css');
writeFileSync(plexTarget, PLEX_CSS);
const plexBuffer = readFileSync(plexTarget);
files.push({
  id: 'plex-mono-css', package: 'generated', version: pkgVersion('@fontsource/ibm-plex-mono'),
  from: 'tools/vendor.mjs', target: 'assets/vendor/ibm-plex-mono/plex-mono.css',
  bytes: plexBuffer.length, sha256: sha(plexBuffer, 'sha256', 'hex'), sha384: sha(plexBuffer, 'sha384', 'base64')
});
console.log(`  ${'ibm-plex-mono/plex-mono.css'.padEnd(52)} ${String((plexBuffer.length / 1024).toFixed(1)).padStart(8)} kB  generated`);

for (const [pkg, from, to] of LICENSES) {
  const source = path.join(MODULES, pkg, from);
  if (!existsSync(source)) {
    console.error(`missing license ${pkg}/${from}`);
    process.exit(1);
  }
  const target = path.join(OUT, to);
  mkdirSync(path.dirname(target), { recursive: true });
  copyFileSync(source, target);
}

const byId = Object.fromEntries(files.map(f => [f.id, f]));
const manifest = {
  note: 'Generated by tools/vendor.mjs — do not edit. Self-hosted third-party front-end libraries (QA-3). Every page load and every lazy load now comes from this origin; there are no CDN requests for the application to fail on and no unpinned third-party code in an authenticated session.',
  versions: [...versions].sort(),
  files,
  load: LOAD.map(entry => {
    const file = byId[entry.id];
    return file ? { ...entry, integrity: `sha384-${file.sha384}` } : entry;
  }),
  /* Read by ensureTabulator() through the #vendor-manifest JSON element that
   * portal.php renders, so a lazily injected script carries SRI too. */
  lazy: {
    tabulatorJs: { src: 'assets/vendor/tabulator/tabulator.min.js', integrity: `sha384-${byId['tabulator-js'].sha384}` },
    tabulatorCss: { href: 'assets/vendor/tabulator/tabulator_midnight.min.css', integrity: `sha384-${byId['tabulator-css'].sha384}` }
  }
};

writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
console.log(`\nvendored ${files.length} files (${manifest.versions.length} packages) + ${LICENSES.length} licenses`);
console.log(`manifest: assets/vendor/VENDOR.json`);
