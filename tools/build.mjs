#!/usr/bin/env node
/**
 * Build tooling for the CallScope reporting dashboard.
 *
 *   node tools/build.mjs             # JS + CSS
 *   node tools/build.mjs --js        # JS bundle only
 *   node tools/build.mjs --css       # stylesheet only
 *   node tools/build.mjs --watch     # rebuild JS on change (dev)
 *
 * Sources -> artifacts (both artifacts are committed, because the deploy is
 * "copy files to the server"; the server never needs Node):
 *
 *   assets/js/src/*.js  --esbuild-->  assets/js/app.js
 *   assets/css/src/app.css --tailwind-->  assets/css/app.css
 *
 * The output paths are deliberately unchanged from before this tooling
 * existed, so index.php/portal.php keep loading the same two files.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JS_ENTRY = path.join(ROOT, 'assets/js/src/app.js');
const JS_OUT = path.join(ROOT, 'assets/js/app.js');
const CSS_ENTRY = path.join(ROOT, 'assets/css/src/app.css');
const CSS_OUT = path.join(ROOT, 'assets/css/app.css');

const args = new Set(process.argv.slice(2));
const watch = args.has('--watch');
const onlyJs = args.has('--js') || (args.size === 0 ? false : args.has('--js'));
const onlyCss = args.has('--css') || (args.size === 0 ? false : args.has('--css'));
const doJs = !onlyCss || onlyJs;
const doCss = !onlyJs || onlyCss;

const fmt = n => (n / 1024).toFixed(1) + ' kB';
const report = (label, file, ms) => {
  const { size } = statSync(file);
  console.log(`  ${label.padEnd(10)} ${path.relative(ROOT, file).padEnd(26)} ${fmt(size).padStart(9)}  ${ms} ms`);
};

function buildJs() {
  const esbuild = path.join(ROOT, 'node_modules/.bin/esbuild');
  if (!existsSync(esbuild)) {
    throw new Error('esbuild not installed — run `npm ci` first.');
  }
  if (!existsSync(JS_ENTRY)) {
    throw new Error(`missing JS entry: ${JS_ENTRY}`);
  }
  const started = Date.now();
  const common = [
    JS_ENTRY,
    '--bundle',
    '--format=iife',
    '--platform=browser',
    '--target=es2020',
    /* React, ReactDOM, Chart.js and Tabulator stay page-level globals (CDN
     * <script> tags); the bundle only contains our own modules. */
    '--banner:js=/* GENERATED by tools/build.mjs from assets/js/src — do not edit. */'
  ];
  if (watch) {
    console.log('watching assets/js/src …');
    execFileSync(esbuild, [...common, `--outfile=${JS_OUT}`, '--watch'], { stdio: 'inherit', cwd: ROOT });
    return;
  }
  execFileSync(esbuild, [...common, `--outfile=${JS_OUT}`, '--log-level=warning'], { cwd: ROOT, stdio: 'inherit' });
  report('js', JS_OUT, Date.now() - started);
}

function buildCss() {
  const tailwind = path.join(ROOT, 'node_modules/.bin/tailwindcss');
  if (!existsSync(tailwind)) {
    throw new Error('@tailwindcss/cli not installed — run `npm ci` first.');
  }
  const started = Date.now();
  execFileSync(tailwind, ['-i', CSS_ENTRY, '-o', CSS_OUT, '--minify=never'], { cwd: ROOT, stdio: 'inherit' });
  report('css', CSS_OUT, Date.now() - started);

  /* A stylesheet that silently loses its component rules is a deploy-time
   * footgun, so fail loudly instead of shipping a broken page. */
  const built = readFileSync(CSS_OUT, 'utf8');
  const REQUIRED = [
    '.q-table', '.hist-table', '.hist-listen', '.aa-tabs', '.sim-panel',
    '.sim-table-scroll', '.call-modal', '.q-pill', '.tn-kpi-mini', '.nav-panel'
  ];
  const missing = REQUIRED.filter(sel => !built.includes(sel));
  if (missing.length) {
    throw new Error(`built stylesheet is missing component selectors: ${missing.join(', ')}`);
  }
}

console.log('building CallScope assets');
if (doJs) buildJs();
if (doCss) buildCss();
console.log('done');
