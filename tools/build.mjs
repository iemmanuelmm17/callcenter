#!/usr/bin/env node
/**
 * Build tooling for the CallScope reporting dashboard.
 *
 *   node tools/build.mjs             # dev: JS + CSS, readable, unversioned
 *   node tools/build.mjs --js        # dev JS bundle only
 *   node tools/build.mjs --css       # dev stylesheet only
 *   node tools/build.mjs --watch     # dev rebuild JS on change
 *   node tools/build.mjs --prod      # deploy: minified, content-hashed + manifest
 *
 * Two modes, on purpose (QA-4):
 *
 *   dev   assets/js/app.js + assets/css/app.css, unminified, fixed names.
 *         git-ignored build output for local work and for the test harness,
 *         which mounts the real bundle in jsdom and needs readable frames.
 *
 *   prod  assets/js/app.<hash>.js + assets/css/app.<hash>.css, minified, the
 *         hash in the name derived from the file's own content, plus
 *         assets/build-manifest.json recording both names and their sha384
 *         integrity hashes. These two files are the committed deploy artifacts
 *         and portal.php loads them from the manifest.
 *
 * The point of the hashed name is that a deploy can be *proved* to have
 * reached a browser: the URL changes whenever the bytes do, so a stale copy is
 * impossible and the server may cache the file forever.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JS_ENTRY = path.join(ROOT, 'assets/js/src/app.js');
const JS_OUT = path.join(ROOT, 'assets/js/app.js');
const CSS_ENTRY = path.join(ROOT, 'assets/css/src/app.css');
const CSS_OUT = path.join(ROOT, 'assets/css/app.css');
const JS_PROD_DIR = path.join(ROOT, 'assets/js');
const CSS_PROD_DIR = path.join(ROOT, 'assets/css');
const MANIFEST = path.join(ROOT, 'assets/build-manifest.json');

const args = new Set(process.argv.slice(2));
const watch = args.has('--watch');
const prod = args.has('--prod');
const check = args.has('--check');
const onlyJs = args.has('--js');
const onlyCss = args.has('--css');
const doJs = !onlyCss || onlyJs;
const doCss = !onlyJs || onlyCss;

if (prod && watch) {
  throw new Error('--prod and --watch are different modes: pick one.');
}
if (check && !prod) {
  throw new Error('--check compares the committed prod artifacts: use `--prod --check`.');
}

const fmt = n => (n / 1024).toFixed(1) + ' kB';
const report = (label, file, ms) => {
  const { size } = statSync(file);
  console.log(`  ${label.padEnd(10)} ${path.relative(ROOT, file).padEnd(34)} ${fmt(size).padStart(9)}  ${ms} ms`);
};
const sha = (file, algorithm, encoding) => createHash(algorithm).update(readFileSync(file)).digest(encoding);
/* Short, filename-safe, derived from the content only. */
const contentHash = file => sha(file, 'sha256', 'hex').slice(0, 10);

function buildJs(target) {
  const esbuild = path.join(ROOT, 'node_modules/.bin/esbuild');
  if (!existsSync(esbuild)) {
    throw new Error('esbuild not installed — run `npm ci` first.');
  }
  if (!existsSync(JS_ENTRY)) {
    throw new Error(`missing JS entry: ${JS_ENTRY}`);
  }
  const started = Date.now();
  const common = [
    JS_ENTRY,
    '--bundle',
    '--format=iife',
    '--platform=browser',
    '--target=es2020',
    /*
     * React, ReactDOM, Chart.js and Tabulator stay page-level globals loaded
     * from assets/vendor by portal.php; the bundle only contains our modules.
     */
    '--banner:js=/* GENERATED by tools/build.mjs from assets/js/src — do not edit. */'
  ];
  if (watch) {
    console.log('watching assets/js/src …');
    execFileSync(esbuild, [...common, `--outfile=${target}`, '--watch'], { stdio: 'inherit', cwd: ROOT });
    return;
  }
  const minify = prod ? ['--minify', '--legal-comments=none'] : [];
  execFileSync(esbuild, [...common, ...minify, `--outfile=${target}`, '--log-level=warning'], { cwd: ROOT, stdio: 'inherit' });
  report(prod ? 'js (prod)' : 'js', target, Date.now() - started);
}

/* A stylesheet that silently loses its component rules is a deploy-time
 * footgun, so fail loudly instead of shipping a broken page. */
const REQUIRED_SELECTORS = [
  '.q-table', '.hist-table', '.hist-listen', '.aa-tabs', '.sim-panel',
  '.sim-table-scroll', '.call-modal', '.q-pill', '.tn-kpi-mini', '.nav-panel'
];
function assertCssComplete(file) {
  const built = readFileSync(file, 'utf8');
  const missing = REQUIRED_SELECTORS.filter(sel => !built.includes(sel));
  if (missing.length) {
    throw new Error(`built stylesheet is missing component selectors: ${missing.join(', ')}`);
  }
}

function buildCss(target) {
  const tailwind = path.join(ROOT, 'node_modules/.bin/tailwindcss');
  if (!existsSync(tailwind)) {
    throw new Error('@tailwindcss/cli not installed — run `npm ci` first.');
  }
  const started = Date.now();
  execFileSync(tailwind, ['-i', CSS_ENTRY, '-o', target, prod ? '--minify' : '--minify=never'], { cwd: ROOT, stdio: 'inherit' });
  assertCssComplete(target);
  report(prod ? 'css (prod)' : 'css', target, Date.now() - started);
}

console.log(prod ? 'building CallScope assets (prod)' : 'building CallScope assets');

if (prod) {
  /* Named by content: build to a scratch name, hash it, then rename. */
  const jsScratch = path.join(JS_PROD_DIR, '.app.prod.js');
  const cssScratch = path.join(CSS_PROD_DIR, '.app.prod.css');
  const previous = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : null;

  if (doJs) buildJs(jsScratch);
  if (doCss) buildCss(cssScratch);

  const entries = {
    js: doJs
      ? { file: 'assets/js/app.' + contentHash(jsScratch) + '.js', scratch: jsScratch, dir: JS_PROD_DIR, prefix: 'app.' }
      : previous?.js,
    css: doCss
      ? { file: 'assets/css/app.' + contentHash(cssScratch) + '.css', scratch: cssScratch, dir: CSS_PROD_DIR, prefix: 'app.' }
      : previous?.css
  };

  if (check) {
    /*
     * --check: the committed artifacts must be exactly what these sources
     * produce. A stale bundle in the repo is the failure mode this catches
     * (someone edits a source, commits, and the browser keeps the old file
     * because the name did not change).
     */
    const problems = [];
    for (const key of ['js', 'css']) {
      const entry = entries[key];
      if (!entry?.scratch) continue;
      const freshHash = contentHash(entry.scratch);
      const wanted = key === 'js' ? `assets/js/app.${freshHash}.js` : `assets/css/app.${freshHash}.css`;
      const committed = previous?.[key];
      if (!committed?.file) problems.push(`${key}: manifest is missing`);
      else if (committed.file !== wanted) problems.push(`${key}: committed ${committed.file}, sources produce ${wanted}`);
      else {
        const onDisk = path.join(ROOT, committed.file);
        if (!existsSync(onDisk)) problems.push(`${key}: ${committed.file} is missing`);
        else if (sha(onDisk, 'sha384', 'base64') !== committed.sha384) problems.push(`${key}: integrity in the manifest does not match the file`);
      }
      rmSync(entry.scratch, { force: true });
    }
    if (problems.length) {
      console.error('prod build is STALE:\n  ' + problems.join('\n  '));
      console.error('run `npm run build:prod` and commit the result');
      process.exit(1);
    }
    console.log('  prod build is up to date (content hashes match the manifest)');
    process.exit(0);
  }

  /* Drop the previous hashed artifact once its replacement is in place, so the
   * repo never accumulates dead bundles. */
  for (const key of ['js', 'css']) {
    const entry = entries[key];
    if (!entry || !entry.scratch) continue;
    const target = path.join(ROOT, entry.file);
    const stale = (previous?.[key]?.file && previous[key].file !== entry.file) ? path.join(ROOT, previous[key].file) : null;
    execFileSync('mv', [entry.scratch, target]);
    if (stale && existsSync(stale)) rmSync(stale);
    entry.bytes = statSync(target).size;
    entry.sha384 = sha(target, 'sha384', 'base64');
  }

  const manifest = {
    note: 'Generated by tools/build.mjs --prod — do not edit. portal.php loads these two files (they are the committed deploy artifacts); the unminified dev build (app.js/app.css) is git-ignored and never served in production.',
    mode: 'prod',
    js: entries.js,
    css: entries.css
  };
  /* Only the deploy-relevant fields — never the absolute paths or scratch
   * names, which would leak the build machine into a committed file. */
  for (const key of ['js', 'css']) {
    delete manifest[key].scratch;
    delete manifest[key].dir;
    delete manifest[key].prefix;
  }
  writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`\nmanifest: assets/build-manifest.json`);
  console.log(`  js  ${entries.js.file}  ${fmt(entries.js.bytes)}`);
  console.log(`  css ${entries.css.file}  ${fmt(entries.css.bytes)}`);
} else {
  if (doJs) buildJs(JS_OUT);
  if (doCss) buildCss(CSS_OUT);
}

console.log('done');
