import assert from 'node:assert/strict';
import { createHarness, FIXTURES } from './harness.mjs';
const tableReview = {id:'job-a',callid:'shown',reason:'SMTP did not confirm acceptance. Delivery is uncertain; verify before retrying.'};
const outsideReview = {id:'review-b',callid:'outside',reason:'No automatic email was sent: the transcription was incomplete.'};
let records = [tableReview, outsideReview, ...Array.from({length:50},(_,i)=>({id:'review-'+i,callid:'older-'+i,reason:'The specific cause was not recorded.'}))];
const page = offset => ({total:records.length,offset:Math.min(offset, Math.floor(Math.max(0,records.length-1)/50)*50),items:records.slice(offset,offset+50)});
const operations=[];
FIXTURES.cache_job = () => ({complete:true,ready:1,total:1});
FIXTURES.intelligence = body => {
  operations.push(body);
  if (body.action === 'monitor_status') return {enabled:true,configured:true,recipients:['alert@example.com'],reviews:page(0)};
  if (body.action === 'monitor_reviews') return page(body.offset);
  if (body.action === 'monitor_reviewed') { records=records.filter(x=>x.id!==body.id); return {reviews:page(body.offset)}; }
  if (body.action === 'watches') return {watches:['urgent']};
  if (body.action === 'list') return {calls:[{reference:'ref',emailReference:'mail',callId:'shown',startedAt:'2026-11-01T10:00:00Z',reviews:[tableReview]}],missing:0,cacheStatus:{complete:true}};
  if (body.action === 'lookup') return {status:'finished',topics:['billing'],summary:'Help',matches:[]};
  return {};
};
const {document,root,flush,click,byText,errors} = await createHarness();
await flush(10); await click(byText('.nav-item','Topics & summaries')); await flush(50);
const row=()=>document.querySelector('[aria-label="Select call shown"]').closest('tr');
assert.match(row().textContent,/Automatic|Needs review/);
assert.match(row().textContent,/Delivery is uncertain/);
assert.match(document.querySelector('.intel-table thead').textContent,/Automatic alert review/);
const section=()=>document.querySelector('[aria-label="Other calls needing review"]');
assert.match(section().textContent,/outside/);
assert(!section().textContent.includes('Call: shown'), 'a review attached to a visible row is not duplicated');
assert.match(section().textContent,/records 1–50 of 52/i);
await click(byText('button','Next reviews')); await flush(10);
assert.match(section().textContent,/records 51–52 of 52/i);
assert.equal(operations.filter(x=>x.action==='monitor_reviews').at(-1).offset,50);
await click(byText('button','Previous reviews')); await flush(10);
await click(row().querySelector('[aria-label="Mark review shown reviewed"]')); await flush(10);
assert.match(row().textContent,/No review recorded/);
assert.match(root().textContent,/No email was sent or retried/);
assert(!section().textContent.includes('Call: shown'));
await click(section().querySelector('[aria-label="Mark review outside reviewed"]')); await flush(10);
assert(!section().textContent.includes('Call: outside'));
assert.equal(operations.filter(x=>x.action==='send').length,0);
assert.equal(errors.length,0,JSON.stringify(errors));
console.log('INTELLIGENCE REVIEWS UI OK — table, separate pages, acknowledgement without resend');
