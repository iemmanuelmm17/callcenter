import assert from 'node:assert/strict';
import React from 'react';
import { unzipSync, strFromU8 } from 'fflate';
import { JSDOM } from 'jsdom';
globalThis.React = React;
const { intelligenceWorkbook } = await import('../../assets/js/src/lib/intelligence-export.js');
const rows = [{ startedAt: '2024-02-29T12:00:00Z', callId: '00123', callerNumber: '0012345', dialedNumber: '=1+2', destinationNumber: '2400', topics: ['a & b'], summary: '=1+2\u0000', status: 'partial', detail: 'not checked', matches: [{ keyword: 'café', source: 'Transcript', excerpt: '<hello> 😊' }] }];
const files = unzipSync(intelligenceWorkbook(rows, [['Scope', 'All & active']]));
const calls = strFromU8(files['xl/worksheets/sheet1.xml']);
const info = strFromU8(files['xl/worksheets/sheet2.xml']);
const dom = new JSDOM('');
const doc = new dom.window.DOMParser().parseFromString(calls, 'application/xml');
assert.equal(doc.querySelector('parsererror'), null);
assert.equal(doc.querySelectorAll('row').length, 2);
assert.equal(doc.querySelector('c[r="G2"] t').textContent, '00123');
assert.equal(doc.querySelector('c[r="I2"] t').textContent, '=1+2');
assert.equal(doc.querySelector('c[r="I2"]').getAttribute('t'), 'inlineStr');
assert.equal(doc.querySelector('c[r="L2"] t').textContent, 'café (Transcript): <hello> 😊');
assert.equal(doc.querySelector('c[r="M2"] t').textContent, 'partial');
assert.equal(doc.querySelector('c[r="C2"] t').textContent, '0012345');
assert.equal(doc.querySelector('c[r="D2"] t').textContent, '=1+2');
assert.equal(doc.querySelector('c[r="D2"]').getAttribute('t'), 'inlineStr');
assert.equal(doc.querySelector('c[r="E2"] t').textContent, '2400');
assert.equal(doc.querySelectorAll('f').length, 0);
assert.match(info, /All &amp; active/);
assert.throws(() => intelligenceWorkbook([{ ...rows[0], summary: 'x'.repeat(32768) }], []), /32,767-character limit/);
console.log('INTELLIGENCE XLSX OK — workbook, escaped Unicode, text-safe cells and limits');
