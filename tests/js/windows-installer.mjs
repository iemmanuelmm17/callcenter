import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const bat = readFileSync('install.bat','utf8');
const ps = readFileSync('tools/install-windows.ps1','utf8');
assert.match(bat, /-NoProfile -ExecutionPolicy Bypass -File "%~dp0tools\\install-windows\.ps1"/);
assert.match(ps, /param\(\[switch\]\$LibraryOnly\)/);
assert.match(ps, /Read-Host \$label -AsSecureString/);
assert.match(ps, /System\.Text\.UTF8Encoding\]::new\(\$false\)/);
assert.match(ps, /'\/XF', 'config\.local\.php'/);
assert.doesNotMatch(ps, /\/MIR\b/i);
assert.match(ps, /if \(\$replaceTask\) \{ \$taskArgs \+= '\/F' \}/);
assert.match(ps, /'\/RU', 'SYSTEM'/);
assert.match(ps, /foreach \(\$segment in @\('', 'includes', 'cache', 'logs', 'tools'\)\)/);
assert.match(ps, /\$status -ne 403 -and \$status -ne 404/);
assert(existsSync('tools/install-check.php'));
assert(existsSync('tests/windows/install-smoke.ps1'));
const template = ps.match(/\$xml = @"\n([\s\S]*?)\n"@/)?.[1];
assert(template, 'scheduled task XML template exists');
const xml = template.replace('${minutes}','5').replace('$start','2026-11-17T12:00:00').replace('$command','C:\\PHP Tools\\php.exe').replace('$argument','&quot;C:\\App &amp; Data\\tools\\intelligence-monitor.php&quot;').replace('$working','C:\\App &amp; Data');
const doc = new JSDOM(xml,{contentType:'text/xml'}).window.document;
const elem = name => doc.getElementsByTagName(name)[0];
assert.equal(elem('UserId').textContent,'S-1-5-18');
assert.equal(elem('Interval').textContent,'PT5M');
assert.equal(elem('MultipleInstancesPolicy').textContent,'IgnoreNew');
assert.equal(elem('Command').textContent,'C:\\PHP Tools\\php.exe');
assert.equal(elem('Arguments').textContent,'"C:\\App & Data\\tools\\intelligence-monitor.php"');
assert.equal(doc.getElementsByTagName('LogonType').length,0,'ServiceAccount is not valid in XML task schema');
assert.deepEqual([...elem('TimeTrigger').children].map(e=>e.localName), ['Enabled','StartBoundary','Repetition']);
console.log('WINDOWS INSTALLER STATIC OK — wrapper, safety, and task XML');
