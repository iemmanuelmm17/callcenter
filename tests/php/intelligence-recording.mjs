import assert from 'node:assert/strict';
import { PhpHarness } from './php.mjs';
const h = await new PhpHarness();
await h.boot();
await h.write('includes/config.local.php', `<?php
define('PBX_SERVERS', ['nms1'=>'https://pbx.example']);
define('INTELLIGENCE_MONITOR_API_KEY', 'secret-service-key');
define('INTELLIGENCE_RECORDING_URL', 'https://calls.example/app/api/intelligence-recording.php');
`);
await h.seedPbx('recording', { 'file-access-url': 'https://pbx.example/ns-api/v2/file?x=1&convert=mp3' });
await h.seedPbx('download', {ok:true,status:200,body:'RIFF1234WAVEaudio',contentType:'audio/wav'});
const init = `require_once TEST_TMP . '/includes/reporting.php'; require_once TEST_TMP . '/includes/intelligence.php'; require_once TEST_TMP . '/includes/intelligence-monitor.php';`;
const created = JSON.parse(await h.script(`${init}
$call=['call-direction'=>1,'call-term-user'=>'sip:222@test.example','call-term-call-id'=>'abc'];
$link=intelligenceRecordingIssue(new PbxClient('key'), 'test.example', $call);
$token=substr($link, strpos($link, '#')+1);
$file=intelligenceRecordingTokenFile($token); $record=intelligenceRecordingResolve($token);
$expired=sprintf('%08x', time()-30*86400) . str_repeat('a', 64);
$tampered=substr($token,0,-1) . (substr($token,-1)==='a'?'b':'a');
echo json_encode(['link'=>$link,'token'=>$token,'record'=>$record,'filename'=>basename($file), 'stored'=>file_get_contents($file), 'tampered'=>intelligenceRecordingResolve($tampered), 'expired'=>intelligenceRecordingResolve($expired), 'future'=>intelligenceRecordingResolve(sprintf('%08x',time()+301).str_repeat('a',64)), 'bad'=>intelligenceRecordingResolve('../invalid'), 'missing'=>intelligenceRecordingIssue(new PbxClient('key'), 'test.example', [])]);
`));
assert.match(created.link, /^https:\/\/calls\.example\/app\/api\/intelligence-recording\.php#[0-9a-f]{72}$/);
assert.equal(created.record.domain, 'test.example');
assert.equal(created.record.user, '222');
assert.equal(created.record.callId, 'abc');
assert(!created.filename.includes(created.token));
assert(!created.stored.includes(created.token));
assert(!created.stored.includes('secret-service-key'));
for (const key of ['tampered','expired','future','bad','missing']) assert.equal(created[key], null, key);
const html = await h.script(`${init} echo intelligenceHighlightHtml('<script>URGENT & urgent?</script>', ['urgent', 'urgent?', '<script>']);`);
assert(!html.includes('<script>'));
assert.match(html, /<mark[^>]*>&lt;script&gt;<\/mark>/);
assert.match(html, /<mark[^>]*>URGENT<\/mark>/);
assert.match(html, /<mark[^>]*>urgent\?<\/mark>/);
const fallback = JSON.parse(await h.script(`${init} echo json_encode(intelligenceAutomaticMessage('test.example', [], ['callid'=>'abc'], ['summary'=>'urgent','topics'=>[],'matches'=>[['keyword'=>'urgent','source'=>'summary','excerpt'=>'urgent']]], null));`));
assert.match(fallback.text, /Recording download link unavailable/);
assert(!fallback.html.includes('Listen to recording'));
assert(!fallback.html.includes('<a href='));
const ok = await h.script(`${init} echo intelligenceRecordingDownload(new PbxClient('key'), intelligenceRecordingResolve('${created.token}')) ?? 'missing';`);
assert.equal(ok.trim(), 'RIFF1234WAVEaudio');
const calls = await h.pbxCalls();
assert(calls.some(c => String(c).includes('download:https://pbx.example/ns-api/v2/file?x=1&convert=wav16')));
await h.seedPbx('download', {ok:true,status:200,body:'not wav',contentType:'audio/wav'});
assert.equal((await h.script(`${init} echo intelligenceRecordingDownload(new PbxClient('key'), intelligenceRecordingResolve('${created.token}')) ?? 'missing';`)).trim(), 'missing');
await h.seedPbx('recording', { 'file-access-url': 'https://127.0.0.1/secret' });
assert.equal((await h.script(`${init} echo intelligenceRecordingDownload(new PbxClient('key'), intelligenceRecordingResolve('${created.token}')) ?? 'missing';`)).trim(), 'missing');
assert.equal((await h.script(`${init} echo intelligenceRecordingIssue(new PbxClient('key'), 'test.example', ['call-direction'=>1,'call-term-user'=>'222','call-term-call-id'=>'abc']) ?? 'missing';`)).trim(), 'missing');
const invalid = await h.script(`$_SERVER['REQUEST_METHOD']='POST'; $_POST=['token'=>'bad']; require TEST_TMP . '/api/intelligence-recording.php';`);
assert.match(invalid, /invalid or expired/);
const landing = await h.script(`$_SERVER['REQUEST_METHOD']='GET'; require TEST_TMP . '/api/intelligence-recording.php';`);
assert.match(landing, /location\.hash/);
await h.seedPbx('recording', { 'file-access-url': 'https://pbx.example/ns-api/v2/file' });
await h.seedPbx('download', {ok:true,status:200,body:'RIFF1234WAVEaudio',contentType:'audio/wav'});
const endpoint = await h.script(`$_SERVER['REQUEST_METHOD']='POST'; $_POST=['token'=>'${created.token}']; require TEST_TMP . '/api/intelligence-recording.php';`);
assert.equal(endpoint.trim(), 'RIFF1234WAVEaudio');
console.log('INTELLIGENCE RECORDING OK — bearer lifetime, escaping, endpoint and WAV validation');
